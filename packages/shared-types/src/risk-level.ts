/**
 * 操作风险等级。
 *
 * - `R0`：只读查询，无副作用；
 * - `R1`：可逆的低风险写入；
 * - `R2`：重要业务写入，需完整审计与幂等保护；
 * - `R3`：高危操作（发薪、付款、权限授予等），需人工确认，
 *   且禁止由 AI 直接执行。
 */
export type RiskLevel = 'R0' | 'R1' | 'R2' | 'R3';

/** 全部风险等级的有序列表，可用于运行时校验。 */
export const RISK_LEVELS: readonly RiskLevel[] = ['R0', 'R1', 'R2', 'R3'];
